"""SEC-03: the gate token. A new random token each start, kept in a 0600 file, compared in constant time.

Tokens here are generated by new_token(); no real credential is used.
"""
from __future__ import annotations

import hmac
import os
import stat
from pathlib import Path

import pytest

from Harpocrates.gate import session_token
from Harpocrates.gate.session_token import (
    TOKEN_HEADER,
    check_token,
    new_token,
    read_token_file,
    write_token_file,
)


def test_sec_03_header_name_is_the_spec_name() -> None:
    assert TOKEN_HEADER == "x-harpo-gate-token"


def test_sec_03_new_token_is_random_long_and_header_safe() -> None:
    first, second = new_token(), new_token()
    assert first != second
    assert len(first) >= 32
    assert set(first) <= set("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_-")


def test_sec_03_token_file_is_0600_and_reads_back(tmp_path: Path) -> None:
    path, token = tmp_path / "gate.token", new_token()
    write_token_file(path, token)
    assert stat.S_IMODE(path.stat().st_mode) == 0o600
    assert read_token_file(path) == token


def test_sec_03_writing_again_replaces_the_token_and_keeps_0600(tmp_path: Path) -> None:
    path = tmp_path / "gate.token"
    write_token_file(path, new_token())
    second = new_token()
    write_token_file(path, second)
    assert read_token_file(path) == second
    assert stat.S_IMODE(path.stat().st_mode) == 0o600
    assert [p.name for p in tmp_path.iterdir()] == ["gate.token"]  # no temp file left behind


def test_sec_03_write_refuses_a_token_the_reader_would_refuse(tmp_path: Path) -> None:
    with pytest.raises(ValueError):
        write_token_file(tmp_path / "gate.token", "short")
    assert not (tmp_path / "gate.token").exists()


def test_sec_03_a_trailing_newline_is_ignored(tmp_path: Path) -> None:
    path, token = tmp_path / "gate.token", new_token()
    path.write_text(token + "\n")
    path.chmod(0o600)
    assert read_token_file(path) == token


@pytest.mark.parametrize("mode", [0o644, 0o640, 0o604, 0o660, 0o666, 0o601])
def test_sec_03_read_refuses_a_file_others_can_reach(tmp_path: Path, mode: int) -> None:
    path, token = tmp_path / "gate.token", new_token()
    write_token_file(path, token)
    path.chmod(mode)
    with pytest.raises(ValueError, match="0600") as caught:
        read_token_file(path)
    assert token not in str(caught.value)


def test_sec_03_read_refuses_a_file_owned_by_someone_else(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    path = tmp_path / "gate.token"
    write_token_file(path, new_token())
    monkeypatch.setattr(os, "geteuid", lambda: os.stat(path).st_uid + 1)
    with pytest.raises(ValueError, match="owned"):
        read_token_file(path)


def test_sec_03_read_refuses_a_missing_file_a_symlink_and_a_directory(tmp_path: Path) -> None:
    real = tmp_path / "real.token"
    write_token_file(real, new_token())
    link = tmp_path / "link.token"
    link.symlink_to(real)
    for bad in (tmp_path / "missing.token", link, tmp_path):
        with pytest.raises(ValueError):
            read_token_file(bad)


@pytest.mark.parametrize("content", ["", "\n", "short", "a" * 31, "a" * 257, "has space " + "a" * 40, "é" * 40,
                                     "a" * 20 + "\n" + "b" * 20])
def test_sec_03_read_refuses_an_empty_short_long_or_odd_token(tmp_path: Path, content: str) -> None:
    path = tmp_path / "gate.token"
    path.write_text(content, encoding="utf-8")
    path.chmod(0o600)
    with pytest.raises(ValueError) as caught:
        read_token_file(path)
    assert content.strip() == "" or content.strip() not in str(caught.value)


def test_sec_03_check_token_accepts_exactly_one_matching_value() -> None:
    expected = new_token()
    assert check_token([expected], expected) is True
    assert check_token([], expected) is False
    assert check_token([expected, expected], expected) is False  # two headers are ambiguous
    assert check_token([expected, "x"], expected) is False


@pytest.mark.parametrize("supplied", ["", "wrong", "TOKEN", "é" * 43, "\x00" * 43])
def test_sec_03_check_token_rejects_wrong_values_without_raising(supplied: str) -> None:
    assert check_token([supplied], new_token()) is False


def test_sec_03_check_token_rejects_a_prefix_and_an_extension() -> None:
    expected = new_token()
    assert check_token([expected[:-1]], expected) is False
    assert check_token([expected + "a"], expected) is False


def test_sec_03_check_token_uses_a_constant_time_compare(monkeypatch: pytest.MonkeyPatch) -> None:
    calls: list[tuple[bytes, bytes]] = []
    real = hmac.compare_digest

    def spy(left: bytes, right: bytes) -> bool:
        calls.append((left, right))
        return real(left, right)

    monkeypatch.setattr(session_token.hmac, "compare_digest", spy)
    expected = new_token()
    assert check_token([expected], expected) is True
    assert check_token(["not-the-token"], expected) is False
    assert len(calls) == 2 and all(isinstance(a, bytes) and isinstance(b, bytes) for a, b in calls)


def test_sec_03_a_failed_write_leaves_no_temporary_file_and_keeps_the_old_token(tmp_path: Path,
                                                                               monkeypatch: pytest.MonkeyPatch) -> None:
    path, first = tmp_path / "gate.token", new_token()
    write_token_file(path, first)

    def refuse(*args: object) -> None:
        raise OSError("disk full")

    monkeypatch.setattr(os, "replace", refuse)
    with pytest.raises(OSError):
        write_token_file(path, new_token())
    assert [p.name for p in tmp_path.iterdir()] == ["gate.token"] and read_token_file(path) == first
