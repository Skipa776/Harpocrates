@pytest.fixture(autouse=True)
def allow_file(tmp_path: Path, tmp_path_factory: pytest.TempPathFactory, monkeypatch: pytest.MonkeyPatch) -> Path:
    monkeypatch.setenv("HOME", str(tmp_path_factory.mktemp("home")))  # FR-READ-06 grants land in this temp home
