def test_fr_read_05_edit_edge_cases(repo, capsys, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    root, canaries = repo
    rel = _secret_file(canaries)
    edit = {"tool_name": "Edit", "cwd": str(root), "permission_mode": "default", "tool_input": {"file_path": rel}}
    assert "Ask the user" in _decision(edit, capsys)[2]  # no --ask (Codex): refused with a way forward
    assert _decision({**edit, "tool_input": {}}, capsys, ask=True)[0] == 2  # malformed input fails closed
    monkeypatch.setenv("HOME", str(root))
    tilde = {**edit, "cwd": str(tmp_path), "tool_input": {"file_path": f"~/{rel}"}}
    assert _decision(tilde, capsys, ask=True)[1] == "ask"
    own = tmp_path / "own.py"  # the shared repo file may be hard-linked by another test, which is always scanned
    own.write_text((root / rel).read_text())
    allowlist.add(own)
    assert _decision({**edit, "tool_input": {"file_path": str(own)}}, capsys, ask=True) == (0, "", "")
    assert "\tEdit\t" in allowlist.LOG_FILE.read_text()
