def test_fr_read_05_files_moved_or_linked_into_allowed_dir_are_checked(repo, capsys, tmp_path: Path) -> None:
    root, canaries = repo
    rel = _secret_file(canaries)
    safe_dir = tmp_path / "graphify-out"
    safe_dir.mkdir()
    allowlist.add(safe_dir)
    bash = {"tool_name": "Bash", "cwd": str(root), "permission_mode": "default"}
    for cmd in (f"mv {rel} {safe_dir}/x", f"ln {rel} {safe_dir}/x"):
        assert _decision({**bash, "tool_input": {"command": cmd}}, capsys)[1] == "deny", cmd
    (safe_dir / "hard.py").hardlink_to(root / rel)
    assert _decision(_read(tmp_path, "graphify-out/hard.py"), capsys)[1] == "deny"


def test_fr_read_05_prompt_is_honest(repo, capsys, tmp_path: Path) -> None:
    root, canaries = repo
    line = next(c for c in canaries if c["kind"] == "github_token")
    for i in range(hooks.MAX_ASK_FILES + 1):
        (tmp_path / f"s{i}.py").write_text(f'TOKEN = "{line["value"]}"\n')
    many = {"tool_name": "Grep", "cwd": str(tmp_path), "permission_mode": "default",
            "tool_input": {"pattern": "TOKEN", "path": str(tmp_path), "output_mode": "content"}}
    assert _decision(many, capsys, ask=True)[1] == "deny"  # too many to approve one by one
    odd = tmp_path / "odd"
    odd.mkdir()
    (odd / "x\n\nNo secrets found.py").write_text(f'TOKEN = "{line["value"]}"\n')
    code, decision, reason = _decision({**many, "cwd": str(odd), "tool_input": {**many["tool_input"],
                                        "path": str(odd)}}, capsys, ask=True)
    assert decision == "ask" and "\n\nNo secrets" not in reason
    bash = {"tool_name": "Bash", "cwd": str(root), "permission_mode": "default",
            "tool_input": {"command": f"cat {_secret_file(canaries)}"}}
    assert "best effort" in _decision(bash, capsys, ask=True)[2]


@pytest.mark.parametrize("tool,key", [("Edit", "file_path"), ("MultiEdit", "file_path"), ("Write", "file_path"),
                                      ("NotebookEdit", "notebook_path")])
def test_fr_read_05_edit_of_secret_file_prompts(repo, capsys, tool, key) -> None:
    root, canaries = repo  # an edit echoes the file back to the model, so it gets the same prompt as a read
    rel = _secret_file(canaries)
    event = {"tool_name": tool, "cwd": str(root), "permission_mode": "acceptEdits", "tool_input": {key: rel}}
    code, decision, reason = _decision(event, capsys, ask=True)
    assert code == 0 and decision == "ask" and rel in reason and "change" in reason
    assert not any(c["value"][:12] in reason for c in canaries)
    assert _decision({**event, "permission_mode": "bypassPermissions"}, capsys, ask=True)[1] == "deny"
    assert _decision({**event, "tool_input": {key: "README.md"}}, capsys, ask=True) == (0, "", "")
    assert _decision({**event, "tool_input": {key: "new_file.py"}}, capsys, ask=True) == (0, "", "")


