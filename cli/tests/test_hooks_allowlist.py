"""FR-READ-05: the user decides. A path on the user's allowlist passes the read hook (each use logged); any
other secret-bearing read prompts the user on Claude Code instead of a flat refusal; the agent can't edit
the allowlist itself.

Canary values are generated by bench/canary_repo.py; none is a real credential.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from bench.canary_repo import build
from Harpocrates import allowlist, hooks


@pytest.fixture(scope="module")
def repo(tmp_path_factory: pytest.TempPathFactory) -> tuple[Path, list[dict]]:
    root = tmp_path_factory.mktemp("canary_repo")
    return root, build(root, seed=7)


@pytest.fixture(autouse=True)
def allow_file(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    monkeypatch.setattr(allowlist, "ALLOW_FILE", tmp_path / "allow")
    monkeypatch.setattr(allowlist, "LOG_FILE", tmp_path / "allow.log")
    return tmp_path / "allow"


def _read(root: Path, rel: str, mode: str = "default") -> dict:
    return {"tool_name": "Read", "cwd": str(root), "permission_mode": mode, "tool_input": {"file_path": rel}}


def _decision(event: dict, capsys: pytest.CaptureFixture, ask: bool = False) -> tuple[int, str, str]:
    code = hooks.decide(json.dumps(event), ask=ask)
    out = capsys.readouterr().out
    if not out:
        return code, "", ""
    spec = json.loads(out)["hookSpecificOutput"]
    return code, spec["permissionDecision"], spec["permissionDecisionReason"]


def _secret_file(canaries: list[dict]) -> str:
    return sorted({c["file"] for c in canaries})[0]


def test_fr_read_05_allowlisted_path_passes_and_is_logged(repo, capsys) -> None:
    root, canaries = repo
    rel = _secret_file(canaries)
    allowlist.add(root / rel)
    assert _decision(_read(root, rel), capsys) == (0, "", "")
    log = allowlist.LOG_FILE.read_text()
    assert str((root / rel).resolve()) in log and "Read" in log
    assert not any(c["value"][:12] in log for c in canaries), "the log must never hold a secret"


def test_fr_read_05_allowlisted_directory_covers_its_tree(repo, capsys) -> None:
    root, canaries = repo
    rel = _secret_file(canaries)
    allowlist.add((root / rel).parent)
    assert _decision(_read(root, rel), capsys) == (0, "", "")
    others = [c["file"] for c in canaries if not (root / c["file"]).resolve().is_relative_to((root / rel).parent.resolve())]
    if others:
        assert _decision(_read(root, others[0]), capsys)[1] == "deny"


def test_fr_read_05_symlink_out_of_allowed_dir_is_still_checked(repo, capsys, tmp_path: Path) -> None:
    root, canaries = repo
    safe_dir = tmp_path / "graphify-out"
    safe_dir.mkdir()
    (safe_dir / "link.py").symlink_to(root / _secret_file(canaries))
    allowlist.add(safe_dir)
    assert _decision(_read(tmp_path, "graphify-out/link.py"), capsys)[1] == "deny"


def test_fr_read_05_ask_mode_prompts_with_every_flagged_file(repo, capsys) -> None:
    root, canaries = repo
    code, decision, reason = _decision(
        {"tool_name": "Grep", "cwd": str(root), "permission_mode": "default",
         "tool_input": {"pattern": ".", "path": str(root), "output_mode": "content"}}, capsys, ask=True)
    assert code == 0 and decision == "ask"
    assert reason.startswith("Harpocrates:") and "harpocrates allow" in reason
    for rel in {c["file"] for c in canaries}:
        assert rel in reason, rel  # the user approves the whole search, so every secret file is named
    assert not any(c["value"][:12] in reason for c in canaries)


