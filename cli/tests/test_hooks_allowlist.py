def _read(root: Path, rel: str, mode: str = "default") -> dict:
    return {"tool_name": "Read", "cwd": str(root), "permission_mode": mode, "tool_input": {"file_path": rel}}


def _decision(event: dict, capsys: pytest.CaptureFixture, ask: bool = False) -> tuple[int, str, str]:
    code = hooks.decide(json.dumps(event), ask=ask)
    out = capsys.readouterr().out
    if not out:
        return code, "", ""
    spec = json.loads(out)["hookSpecificOutput"]
    return code, spec["permissionDecision"], spec["permissionDecisionReason"]


def _secret_file(canaries: list[dict]) -> str:
    return sorted({c["file"] for c in canaries})[0]


def test_fr_read_05_allowlisted_path_passes_and_is_logged(repo, capsys) -> None:
    root, canaries = repo
    rel = _secret_file(canaries)
    allowlist.add(root / rel)
    assert _decision(_read(root, rel), capsys) == (0, "", "")
    log = allowlist.LOG_FILE.read_text()
    assert str((root / rel).resolve()) in log and "Read" in log
    assert not any(c["value"][:12] in log for c in canaries), "the log must never hold a secret"


def test_fr_read_05_allowlisted_directory_covers_its_tree(repo, capsys) -> None:
    root, canaries = repo
    rel = _secret_file(canaries)
    allowlist.add((root / rel).parent)
    assert _decision(_read(root, rel), capsys) == (0, "", "")
    others = [c["file"] for c in canaries if not (root / c["file"]).resolve().is_relative_to((root / rel).parent.resolve())]
    if others:
        assert _decision(_read(root, others[0]), capsys)[1] == "deny"


