    allowed = ["rg --files", "rg -l TOKEN", "rg -n TOKEN README.md", "python -c 'print(1)'",
               "/bin/zsh -lc 'git status'", "pytest -q"]
    for cmd in allowed:
        assert _run(bash(cmd), capsys) == (0, ""), cmd


