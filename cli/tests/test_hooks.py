def _run(event: dict, capsys: pytest.CaptureFixture) -> tuple[int, str]:
    code = hooks.decide(json.dumps(event))
    return code, capsys.readouterr().out


def _denied(out: str) -> bool:
    return bool(out) and json.loads(out)["hookSpecificOutput"]["permissionDecision"] == "deny"


def test_fr_read_03_hook_blocks_read_of_file_with_secret(repo, capsys) -> None:
    root, canaries = repo
    for rel in sorted({c["file"] for c in canaries}):
        code, out = _run({"tool_name": "Read", "cwd": str(root), "tool_input": {"file_path": rel}}, capsys)
        assert code == 0 and _denied(out), rel
        assert "safe_read" in out
        assert not any(c["value"][:12] in out for c in canaries), "the hook must never echo a secret"


