"""FR-READ-03: the Claude Code PreToolUse hook blocks built-in reads of files that contain a secret.

Canary values are generated by bench/canary_repo.py; none is a real credential.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from bench.canary_repo import build
from Harpocrates import hooks


@pytest.fixture(scope="module")
def repo(tmp_path_factory: pytest.TempPathFactory) -> tuple[Path, list[dict]]:
    root = tmp_path_factory.mktemp("canary_repo")
    return root, build(root, seed=7)


def _run(event: dict, capsys: pytest.CaptureFixture) -> tuple[int, str]:
    code = hooks.decide(json.dumps(event))
    return code, capsys.readouterr().out


def _denied(out: str) -> bool:
    return bool(out) and json.loads(out)["hookSpecificOutput"]["permissionDecision"] == "deny"


def test_fr_read_03_hook_blocks_read_of_file_with_secret(repo, capsys) -> None:
    root, canaries = repo
    for rel in sorted({c["file"] for c in canaries}):
        code, out = _run({"tool_name": "Read", "cwd": str(root), "tool_input": {"file_path": rel}}, capsys)
        assert code == 0 and _denied(out), rel
        assert "safe_read" in out
        assert not any(c["value"][:12] in out for c in canaries), "the hook must never echo a secret"


def test_fr_read_03_hook_allows_clean_file(repo, capsys) -> None:
    root, _ = repo
    code, out = _run({"tool_name": "Read", "cwd": str(root), "tool_input": {"file_path": "README.md"}}, capsys)
    assert code == 0 and out == ""


def test_fr_read_03_hook_grep_content_mode(repo, capsys) -> None:
    root, _ = repo
    content = {"tool_name": "Grep", "cwd": str(root),
               "tool_input": {"pattern": "TOKEN", "path": str(root), "output_mode": "content"}}
    code, out = _run(content, capsys)
    assert code == 0 and _denied(out) and "safe_grep" in out
    names_only = {**content, "tool_input": {**content["tool_input"], "output_mode": "files_with_matches"}}
    assert _run(names_only, capsys) == (0, "")  # file names carry no secret
    clean = {**content, "tool_input": {**content["tool_input"], "pattern": "docker compose"}}
    assert _run(clean, capsys) == (0, "")


def test_fr_read_03_hook_bash_file_reads(repo, capsys) -> None:
    root, _ = repo
    def bash(cmd: str) -> dict:
        return {"tool_name": "Bash", "cwd": str(root), "tool_input": {"command": cmd}}
    for cmd in ("cat config/settings.py", "ls && head -n 5 src/client.js", "grep -n TOKEN < config/settings.py"):
        code, out = _run(bash(cmd), capsys)
        assert code == 0 and _denied(out), cmd
    for cmd in ("ls -la", "cat README.md", "git status"):
        assert _run(bash(cmd), capsys) == (0, ""), cmd


def test_fr_read_03_hook_fails_closed(repo, capsys, monkeypatch: pytest.MonkeyPatch) -> None:
    root, _ = repo
    assert hooks.decide("not json") == 2
    import Harpocrates.read as read

    monkeypatch.setattr(read.Redactor, "redact", lambda *_a: (_ for _ in ()).throw(RuntimeError("boom")))
    code = hooks.decide(json.dumps({"tool_name": "Read", "cwd": str(root), "tool_input": {"file_path": "README.md"}}))
    assert code == 2
    assert "boom" not in capsys.readouterr().out


def test_fr_read_03_hook_bash_codex_style_commands(repo, capsys) -> None:
    """Codex wraps commands in `zsh -lc` and loops over files; ripgrep searches the tree."""
    root, _ = repo
    def bash(cmd: str) -> dict:
        return {"tool_name": "Bash", "cwd": str(root), "tool_input": {"command": cmd}}
    blocked = ["/bin/zsh -lc 'for f in config/settings.py src/client.js; do nl -ba \"$f\"; done'",
               "bash -c \"sed -n '1,50p' src/client.js\"",
               "rg -n TOKEN", "grep -rn TOKEN .", "rg -e stripe config",
               "rg -n 'docker compose'"]  # shell searches never evaluate the pattern: whole scope counts
    for cmd in blocked:
        code, out = _run(bash(cmd), capsys)
        assert code == 0 and _denied(out), cmd
    allowed = ["rg --files", "rg -l TOKEN", "rg -n TOKEN README.md", "python -c 'print(1)'",
               "/bin/zsh -lc 'git status'", "pytest -q"]
    for cmd in allowed:
        assert _run(bash(cmd), capsys) == (0, ""), cmd


def _bash(root: Path, cmd: str) -> dict:
    return {"tool_name": "Bash", "cwd": str(root), "tool_input": {"command": cmd}}


