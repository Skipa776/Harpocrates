def test_fr_read_03_hook_grep_semantics_fail_safe(repo, capsys, tmp_path: Path) -> None:
    root, _ = repo
    for extra in ({"pattern": "^AWS_SECRET"}, {"pattern": "aws_secret", "-i": True},
                  {"pattern": "[[:alpha:]]+"}, {"pattern": "(a+)+$"}):
        event = {"tool_name": "Grep", "cwd": str(root),
                 "tool_input": {"path": str(root), "output_mode": "content", **extra}}
        code, out = _run(event, capsys)
        assert code == 0 and _denied(out), extra
    big = tmp_path / "big.txt"
    big.write_text("x" * (11 * 1024 * 1024) + "\nAKIA" + "Q" * 16 + "\n")
    event = {"tool_name": "Grep", "cwd": str(tmp_path),
             "tool_input": {"pattern": "AKIA", "path": str(tmp_path), "output_mode": "content"}}
    code, out = _run(event, capsys)
    assert code == 0 and _denied(out)


def test_fr_read_03_hook_bash_review_cases(repo, capsys) -> None:
    root, _ = repo
    blocked = ["sudo bash -c 'cat .env'", "env bash -c 'cat .env'", "timeout 5 bash -c 'cat .env'",
               'echo "$(cat .env)"', "cat `echo .env`", "cd config && cat settings.py", "cat config/*",
               "cat ~/../../" + str(root).lstrip("/") + "/.env", "git show HEAD:config/settings.py",
               "dd if=.env", "cp .env /dev/stdout", "xargs -a .env echo", "rg -m 7 TOKEN .",
               "rg -t py TOKEN .", "rg -g '*.py' TOKEN"]
    for cmd in blocked:
        code, out = _run(_bash(root, cmd), capsys)
        assert code == 0 and _denied(out), cmd
    for cmd in ("cd config && ls", "git status", "rg -l TOKEN"):
        assert _run(_bash(root, cmd), capsys) == (0, ""), cmd


def test_fr_read_03_hook_environment(repo, capsys, monkeypatch: pytest.MonkeyPatch) -> None:
    root, canaries = repo
    token = next(c["value"] for c in canaries if c["kind"] == "github_token")
    monkeypatch.setenv("GITHUB_TOKEN", token)
    for cmd in ("env", "printenv", "echo $GITHUB_TOKEN", "echo ${GITHUB_TOKEN}", "cat /proc/self/environ"):
        code, out = _run(_bash(root, cmd), capsys)
        assert code == 0 and _denied(out) and token not in out, cmd
    assert _run(_bash(root, "echo $HOME"), capsys) == (0, "")


def test_fr_read_03_hook_match_timeout_counts_as_match(repo, capsys, monkeypatch: pytest.MonkeyPatch) -> None:
    """A pattern that stalls the matcher must not stall the hook into its own timeout (= allow)."""
    import subprocess

    root, _ = repo
    def stall(*_a, **kw):
        raise subprocess.TimeoutExpired(cmd="matcher", timeout=kw.get("timeout", 0))
    monkeypatch.setattr(hooks.subprocess, "run", stall)
    event = {"tool_name": "Grep", "cwd": str(root),
             "tool_input": {"pattern": "docker compose", "path": str(root), "output_mode": "content"}}
    code, out = _run(event, capsys)
    assert code == 0 and _denied(out)


def test_fr_read_03_hook_rereview_cases(repo, capsys, monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    root, canaries = repo
    blocked = ["rg --regexp=AWS_SECRET .env", "grep -eAWS_SECRET .env", "rg -nA 3 AWS_SECRET .env",
               "rg -v zzzz .env", "rg --passthru zzzz .env", "grep -E -v zzzz .env", "bash -x -c 'cat .env'",
               "bash --noprofile -c 'cat .env'", "eval 'cat .env'", "git grep AWS HEAD", "git blame .env"]
    for cmd in blocked:
        code, out = _run(_bash(root, cmd), capsys)
        assert code == 0 and _denied(out), cmd
    token = next(c["value"] for c in canaries if c["kind"] == "github_token")
    monkeypatch.setenv("GITHUB_TOKEN", token)
    for cmd in ('echo "$(printenv)"', "bash -c 'echo hi; env'"):
        code, out = _run(_bash(root, cmd), capsys)
        assert code == 0 and _denied(out) and token not in out, cmd
    assert _run(_bash(root, "git config set user.name x"), capsys) == (0, "")
    odd = tmp_path / "a\nb.txt"
    odd.write_text("AWS_ACCESS_KEY_ID=AKIA" + "QZ7XK2PLM9RT4VWB" + "\n")
    event = {"tool_name": "Grep", "cwd": str(tmp_path),
             "tool_input": {"pattern": "AWS", "path": str(tmp_path), "output_mode": "content"}}
    code, out = _run(event, capsys)
    assert code == 0 and _denied(out)
