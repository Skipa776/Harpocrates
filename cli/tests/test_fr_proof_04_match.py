"""FR-PROOF-04: finding planted canaries in recorded request bodies, and saying where, without ever writing a value.

The canaries here are generated by bench/canaries/secret_templates.py; nothing is a real credential.
"""
from __future__ import annotations

import base64
import json
import random
import urllib.parse

import pytest

from bench import canary_match as match
from bench import canary_repo

PEM = "-----BEGIN RSA PRIVATE KEY-----\n" + "\n".join(["abcdEFGH0123+/ijklMNOPqrstUVWX4567" * 2] * 3) + "\n-----END RSA PRIVATE KEY-----"
TOKEN = "ghp_" + "Ab3dE5gH7jK9mN1pQ3sT5vX7zB9cD1fG3hJ5"


def test_fr_proof_04_match_every_repo_canary_kind_has_a_class() -> None:
    random.seed(3)
    kinds = set(canary_repo._canaries())
    assert kinds == match.KNOWN_FORMAT_KINDS | match.ML_ONLY_KINDS
    assert not match.KNOWN_FORMAT_KINDS & match.ML_ONLY_KINDS
    assert match.kind_class("github_token") == "known-format" and match.kind_class("db_password") == "ml-only"
    with pytest.raises(ValueError):
        match.kind_class("surprise")


def test_fr_proof_04_match_finds_the_plain_value_in_a_nested_body_and_names_the_place() -> None:
    body = {"model": "m", "messages": [
        {"role": "user", "content": "hello"},
        {"role": "user", "content": [{"type": "tool_result", "tool_use_id": "t1",
                                      "content": [{"type": "text", "text": f"GITHUB_TOKEN={TOKEN}\nDEBUG=1"}]}]}]}
    hits = match.locate(json.dumps(body), TOKEN)
    assert hits == [match.Hit("messages[1].content[0].content[0].text", "text", "plain")]
    assert match.locate(json.dumps(body), TOKEN + "x") == []


def test_fr_proof_04_match_says_string_content_and_system_by_their_place() -> None:
    body = {"system": f"key {TOKEN}", "messages": [{"role": "user", "content": f"use {TOKEN}"}]}
    hits = {h.path: h.block_type for h in match.locate(json.dumps(body), TOKEN)}
    assert hits == {"system": "system", "messages[0].content": "message(user)"}


def test_fr_proof_04_match_finds_a_value_inside_json_in_a_string_and_a_multiline_value() -> None:
    args = json.dumps({"cmd": f"echo {TOKEN}", "env": {"KEY": PEM}})
    body = {"input": [{"type": "function_call", "call_id": "c1", "name": "exec_command", "arguments": args}]}
    assert [(h.path, h.block_type) for h in match.locate(json.dumps(body), TOKEN)] == [
        ("input[0].arguments{json}.cmd", "function_call")]
    assert [(h.path, h.form) for h in match.locate(json.dumps(body), PEM)] == [("input[0].arguments{json}.env.KEY", "plain")]


def test_fr_proof_04_match_a_key_that_holds_the_value_is_not_written_into_the_path() -> None:
    body = {"input": [{"type": "function_call", "arguments": json.dumps({TOKEN: 1, "ok_key": TOKEN})}]}
    hits = match.locate(json.dumps(body), TOKEN)
    assert {h.path for h in hits} == {"input[0].arguments{json}.<key>", "input[0].arguments{json}.ok_key"}
    assert TOKEN not in json.dumps([h._asdict() for h in hits])
    odd = {"a b/c d": TOKEN}
    assert [h.path for h in match.locate(json.dumps(odd), TOKEN)] == ["<key>"]


def test_fr_proof_04_match_finds_encoded_forms() -> None:
    forms = {"base64": base64.b64encode(TOKEN.encode()).decode(), "hex": TOKEN.encode().hex(),
             "urlencoded": urllib.parse.quote("pa$$/word:" + TOKEN, safe="")}
    for form, text in forms.items():
        hits = match.locate(json.dumps({"input": text}), "pa$$/word:" + TOKEN if form == "urlencoded" else TOKEN)
        assert [h.form for h in hits] == [form], form


def test_fr_proof_04_match_a_multiline_value_counts_when_one_long_line_leaks() -> None:
    lines = PEM.splitlines()
    leaked = {"text": "here: " + lines[2]}  # one base64 line, no armor
    hits = match.locate(json.dumps(leaked), PEM)
    assert [(h.path, h.form) for h in hits] == [("text", "line")]
    armor_only = {"text": lines[0] + " " + lines[-1]}
    assert match.locate(json.dumps(armor_only), PEM) == []  # the BEGIN and END lines alone are not the key


def test_fr_proof_04_match_a_value_in_a_body_that_is_not_json_is_still_found() -> None:
    hits = match.locate(f"not json at all {TOKEN}", TOKEN)
    assert hits == [match.Hit("(unparsed body)", "(unparsed)", "plain")]
    assert match.locate("", TOKEN) == []
    assert match.locate("[1,2,3]", TOKEN) == []


def test_fr_proof_04_match_a_short_or_empty_value_never_matches() -> None:
    assert match.locate(json.dumps({"a": "xx"}), "") == []
    assert match.locate(json.dumps({"a": "xx"}), "xx") == []  # under the 8-character floor: too likely to be chance


def test_fr_proof_04_match_a_value_split_by_redaction_is_not_found() -> None:
    redacted = {"text": "GITHUB_TOKEN=<<HARPO:github_token:ab12>>"}
    assert match.locate(json.dumps(redacted), TOKEN) == []
