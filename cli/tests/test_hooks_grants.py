def test_fr_read_06_grants_older_than_a_day_are_ignored_and_pruned(proj: Path, home: Path, capsys) -> None:
    _grant(proj, capsys)
    real = str((proj / "app.py").resolve())
    state = _state(home)
    state["granted"][real] = time.time() - 25 * 3600
    state["pending"]["stale"] = {"path": real, "tool": "Edit", "ts": time.time() - 25 * 3600}
    _file(home).write_text(json.dumps(state))
    assert _decision(_read(proj), capsys)[1] == "deny"
    assert _post(tuid="stale") == 0  # a stale pending cannot be promoted
    assert _decision(_read(proj, "other.py"), capsys)[1] == "deny"
    assert _decision(_edit(proj, "other.py", tuid="fresh"), capsys)[1] == "ask"  # a write prunes what expired
    state = _state(home)
    assert real not in state["granted"] and "stale" not in state["pending"] and "fresh" in state["pending"]


