def test_fr_read_06_edit_that_keeps_an_existing_placeholder_is_allowed(proj: Path, capsys) -> None:
    doc = proj / "docs.md"
    doc.write_text(f"see {PLACEHOLDER} for the shape\nline two\n")
    edits = [
        _pre("Edit", proj, {"file_path": "docs.md", "old_string": "line two", "new_string": "line 2"}),
        _pre("Edit", proj, {"file_path": "docs.md", "old_string": f"see {PLACEHOLDER} for",
                            "new_string": f"read {PLACEHOLDER} for"}),  # rewords the line, the placeholder stays
        _pre("Write", proj, {"file_path": "docs.md", "content": f"# notes\nsee {PLACEHOLDER} for the shape\n"}),
        _pre("Write", proj, {"file_path": "docs.md", "content": f"line two\n{PLACEHOLDER}\n"}),  # moved, not added
        _pre("Edit", proj, {"file_path": "docs.md", "old_string": PLACEHOLDER, "new_string": "removed"}),
    ]
    for event in edits:
        assert _decision(event, capsys) == (0, "", ""), event["tool_input"]
    more = _pre("Edit", proj, {"file_path": "docs.md", "old_string": "line two",
                               "new_string": f"line two {PLACEHOLDER}"})  # a second copy is new
    assert _decision(more, capsys) == (0, "deny", PLACEHOLDER_DENY)
    swap = _pre("Edit", proj, {"file_path": "docs.md", "old_string": PLACEHOLDER,
                               "new_string": PLACEHOLDER[:-6] + "ffff>>"})  # a different fake value is new too
    assert _decision(swap, capsys) == (0, "deny", PLACEHOLDER_DENY)


