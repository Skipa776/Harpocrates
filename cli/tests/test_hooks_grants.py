def _split(point: int = 6) -> tuple[str, str]:
    """A placeholder in two pieces, neither of which matches the placeholder pattern alone."""
    assert not hooks._PLACEHOLDER_TYPE.search(PLACEHOLDER[:point] + "x")
    return PLACEHOLDER[:point], PLACEHOLDER[point:]


def test_fr_read_06_placeholder_split_across_two_edits_is_denied(proj: Path, capsys) -> None:
    head, tail = _split()
    doc = proj / "notes.md"
    doc.write_text("top ANCHOR bottom\n")
    first = _pre("Edit", proj, {"file_path": "notes.md", "old_string": "ANCHOR", "new_string": head + "TAIL"})
    assert _decision(first, capsys) == (0, "", "")  # no complete placeholder yet
    doc.write_text(f"top {head}TAIL bottom\n")  # the first edit ran
    second = _pre("Edit", proj, {"file_path": "notes.md", "old_string": "TAIL", "new_string": tail}, tuid="t2")
    assert _decision(second, capsys) == (0, "deny", PLACEHOLDER_DENY)  # the new text alone is clean; the result is not


def test_fr_read_06_placeholder_split_inside_one_multiedit_or_write_is_denied(proj: Path, capsys) -> None:
    head, tail = _split()
    (proj / "notes.md").write_text("top ANCHOR bottom\n")
    multi = _pre("MultiEdit", proj, {"file_path": "notes.md", "edits": [
        {"old_string": "ANCHOR", "new_string": head + "TAIL"}, {"old_string": "TAIL", "new_string": tail}]})
    assert _decision(multi, capsys) == (0, "deny", PLACEHOLDER_DENY)  # the second edit sees the first one's result
    twice = _pre("Edit", proj, {"file_path": "notes.md", "old_string": "o", "new_string": PLACEHOLDER[:2],
                                "replace_all": True})
    assert _decision(twice, capsys) == (0, "", "")  # pieces that never join are fine
    (proj / "joined.md").write_text(f"{head}\n")
    write = _pre("Write", proj, {"file_path": "joined.md", "content": head + tail})
    assert _decision(write, capsys) == (0, "deny", PLACEHOLDER_DENY)


def test_fr_read_06_edit_that_cannot_be_applied_falls_back_to_the_new_text(proj: Path, capsys) -> None:
    (proj / "notes.md").write_text("nothing to match here\n")
    event = _pre("Edit", proj, {"file_path": "notes.md", "old_string": "absent", "new_string": f"x {PLACEHOLDER}"})
    assert _decision(event, capsys) == (0, "deny", PLACEHOLDER_DENY)
    clean = _pre("Edit", proj, {"file_path": "notes.md", "old_string": "absent", "new_string": "fine"})
