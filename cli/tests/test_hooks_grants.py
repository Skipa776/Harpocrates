@pytest.mark.parametrize("tool,key,extra", EDITS)
def test_fr_read_06_placeholder_in_new_content_is_denied_always(proj: Path, capsys, tool, key, extra) -> None:
    def with_placeholder(rel: str, **kw) -> dict:
        event = _edit(proj, rel, tool=tool, **kw)
        text = f"TOKEN = '{PLACEHOLDER}'"
        if tool == "MultiEdit":
            event["tool_input"]["edits"] = [{"old_string": "x", "new_string": "ok"}, {"old_string": "y", "new_string": text}]
        else:
            field = next(f for f in ("new_string", "content", "new_source") if f in event["tool_input"])
            event["tool_input"][field] = text
        return event

    def denied(event: dict, ask: bool = True) -> None:
        assert _decision(event, capsys, ask=ask) == (0, "deny", PLACEHOLDER_DENY)

    denied(with_placeholder("README.md"))  # a clean file
    denied(with_placeholder("new_file.py"))
    denied(with_placeholder("README.md", mode="bypassPermissions"), ask=False)
    _grant(proj, capsys)
    denied(with_placeholder("app.py", tuid="tu-9"))  # granted, still denied
    allowlist.add(proj / "other.py")
    denied(with_placeholder("other.py", tuid="tu-8"))  # allowlisted, still denied
    plain = _edit(proj, "README.md", tool=tool)
    assert _decision(plain, capsys) == (0, "", "")


