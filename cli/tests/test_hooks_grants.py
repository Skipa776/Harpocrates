def test_fr_read_06_post_entry_point_is_silent_and_never_fails(proj: Path, home: Path, capsys,
                                                               child_python) -> None:
    env = {**os.environ, "HOME": str(home)}

    def run(stdin: bytes) -> subprocess.CompletedProcess:
        return subprocess.run(child_python("Harpocrates.hooks", "--post"), input=stdin,
                              capture_output=True, env=env)

    for junk in (b"\xff\xfe", b"", b"not json", b"[]", b'{"hook_event_name": "PostToolUse", "session_id": 5}'):
        proc = run(junk)
        assert (proc.returncode, proc.stdout, proc.stderr) == (0, b"", b""), junk
    assert _decision(_edit(proj), capsys)[1] == "ask"
    event = {"hook_event_name": "PostToolUse", "session_id": SID, "tool_use_id": TUID, "tool_name": "Edit"}
    proc = run(json.dumps(event).encode())
    assert (proc.returncode, proc.stdout, proc.stderr) == (0, b"", b"")
    assert list(_state(home)["granted"]) == [str((proj / "app.py").resolve())]
    proc = run(json.dumps({"hook_event_name": "SessionEnd", "session_id": SID}).encode())
    assert (proc.returncode, proc.stdout, proc.stderr) == (0, b"", b"")
    assert not _file(home).exists()


